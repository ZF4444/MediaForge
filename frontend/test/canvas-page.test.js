import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';

describe('canvas page entry', () => {
  it('owns the canvas shell in frontend and uses npm compatibility dependencies', () => {
    const html = readFileSync(resolve(process.cwd(), 'src/pages/canvas/index.html'), 'utf8');
    const runtime = readFileSync(resolve(process.cwd(), 'src/canvas/runtime.js'), 'utf8');
    const source = readFileSync(resolve(process.cwd(), 'src/canvas/main.js'), 'utf8');
    const render = readFileSync(resolve(process.cwd(), 'src/canvas/canvas-render.js'), 'utf8');
    const syncSocket = readFileSync(resolve(process.cwd(), 'src/canvas/canvas-sync-socket.js'), 'utf8');
    const assetLibrary = readFileSync(resolve(process.cwd(), 'src/canvas/asset-library.js'), 'utf8');
    const loopNode = readFileSync(resolve(process.cwd(), 'src/canvas/loop-node.js'), 'utf8');
    const imageEditor = readFileSync(resolve(process.cwd(), 'src/canvas/image-editor.js'), 'utf8');
    const generationSettings = readFileSync(resolve(process.cwd(), 'src/canvas/generation-settings.js'), 'utf8');
    const mentionComposer = readFileSync(resolve(process.cwd(), 'src/canvas/mention-composer.js'), 'utf8');
    expect(html).toContain('../../canvas/runtime.js');
    expect(html).toContain('/static/dist/shared/theme-bootstrap-early.js');
    expect(html).toContain('type="module" blocking="render"');
    expect(html).not.toMatch(/<script>\s*[\s\S]*?<\/script>/i);
    expect(html).not.toMatch(/\sstyle=/i);
    expect(html).not.toContain('/static/vendor/js/lucide.js');
    expect(html).not.toContain('/static/vendor/js/marked-18.0.6.umd.js');
    expect(html).not.toContain('/static/vendor/js/dompurify-3.4.12.min.js');
    expect(html).toContain('../../canvas/runtime.js');
    expect(html).not.toContain('/static/dist/canvas/main.js');
    expect(html).not.toContain('/static/dist/canvas/state.js');
    expect(html).not.toContain('/static/dist/canvas/agent/agent-panel.js');
    for (const id of ['canvasShortcutToggle', 'canvasLogToggle', 'canvasLogModal', 'canvasShortcutModal']) {
      expect(html).not.toMatch(new RegExp(`id="${id}"[^>]*on(?:click|input|change)=`, 'i'));
    }
    const config = readFileSync(resolve(process.cwd(), 'vite.config.js'), 'utf8');
    expect(config).toContain("import { createIcons, icons } from 'lucide';");
    expect(config).toContain("import * as THREE from 'three';");
    expect(config).toContain("replaceAll('window.StudioI18n', 'StudioI18n')");
    expect(config).toContain("replaceAll('window.focusCanvasNode', 'focusCanvasNode')");
    expect(config).toContain('let CanvasAgentState, CanvasAgentBridge');
    expect(source).not.toContain('window.onload =');
    expect(source).not.toContain('window.__canvasPanoramaState');
    expect(source).not.toMatch(/function connectAssetLibrarySyncSocket\s*\(/);
    expect(source).not.toMatch(/promptPreset(?:Apply|Save|New|Delete)\.onclick/);
    expect(source).toContain("promptPresetApply.addEventListener('click'");
    expect(source).toContain("promptPresetSave.addEventListener('click'");
    expect(source).toContain("promptPresetNew.addEventListener('click'");
    expect(source).toContain("promptPresetDelete.addEventListener('click'");
    expect(syncSocket).toContain('function connectAssetLibrarySyncSocket');
    expect(syncSocket).not.toContain('socket.onmessage');
    expect(syncSocket).toContain("socket.addEventListener('message'");
    expect(source).not.toContain('apiChannel.onmessage');
    expect(assetLibrary).not.toMatch(/assetDialog(?:Ok|Cancel)\.onclick/);
    expect(assetLibrary).not.toContain('assetDialogInput.onkeydown');
    expect(assetLibrary).not.toMatch(/btn\.onclick/);
    expect(assetLibrary).toContain("btn.addEventListener('click'");
    expect(assetLibrary).toContain("assetDialogOk.addEventListener('click', confirmHandler)");
    expect(loopNode).not.toMatch(/(?:btn|input|text)\.(onclick|oninput|onchange|onfocus)\s*=/);
    expect(loopNode).toContain("btn.addEventListener('click'");
    expect(loopNode).toContain("input.addEventListener('input'");
    expect(loopNode).toContain("text.addEventListener('focus'");
    expect(source).toContain("window.addEventListener('load', windowLoadHandler");
    expect(source).not.toMatch(/shell\.(onmousedown|oncontextmenu|ondblclick|onclick|ondragover|ondrop)\s*=/);
    expect(source).toContain("shell.addEventListener('mousedown', shellMousedownHandler3)");
    expect(source).toContain("shell.addEventListener('drop', shellDropHandler)");
    expect(source).not.toMatch(/(?:assetLibrarySelect|assetCategorySelect|assetAddCategoryBtn|assetRenameCategoryBtn)\.(onclick|onchange)\s*=/);
    expect(source).toContain("assetLibrarySelect.addEventListener('change'");
    expect(source).toContain("assetAddCategoryBtn.addEventListener('click'");
    expect(source).not.toMatch(/(?:el|btn|textEl)\.(onclick|oninput)\s*=/);
    expect(source).toContain("textEl.addEventListener('input'");
    expect(render).not.toMatch(/window\.onmousemove\s*=/);
    expect(render).not.toMatch(/window\.onmouseup\s*=/);
    expect(render).not.toMatch(/\bel\.(onclick|ondblclick|onmousedown|ondragover|ondrop)\s*=/);
    expect(render).toContain("el.addEventListener('click'");
    expect(render).toContain("el.addEventListener('dblclick'");
    expect(render).toContain("el.addEventListener('mousedown', beginNodeDrag)");
    expect(render).toContain("el.addEventListener('dragover'");
    expect(render).toContain("el.addEventListener('drop'");
    expect(render).toContain("window.addEventListener('mousemove', handleWindowMouseMove)");
    expect(render).toContain("window.addEventListener('mouseup', handleWindowMouseUp)");
    expect(render).not.toContain('input.onchange');
    expect(render).toContain("input.addEventListener('change'");
    expect(imageEditor).toContain("btn.addEventListener('click'");
    expect(imageEditor).not.toContain('btn.onclick');
    expect(imageEditor).not.toMatch(/\.(onload|onerror|onloadedmetadata|onloadeddata)\s*=/);
    expect(imageEditor).toContain('setImageEditorListener');
    expect(generationSettings).not.toMatch(/\\.(onclick|onchange|oninput|onpointerup|onmouseleave)\\s*=/);
    expect(generationSettings).toContain("addEventListener('change'");
    expect(mentionComposer).not.toMatch(/(?:promptTaskSelect|promptComposerInstruction|modelPill|modelEl|ruleEl|promptComposerRunBtn)\.(onclick|onchange|oninput)\s*=/);
    expect(mentionComposer).toContain("promptComposerRunBtn.addEventListener('click'");
    expect(runtime).toContain("import * as canvasActions from 'virtual:canvas-features';");
    expect(runtime).not.toMatch(/window\.(lucide|THREE|marked|DOMPurify)/);
    expect(html).not.toContain('/static/vendor/js/three-0.160.0.module.js');
    expect(html).not.toContain('/static/dist/shared/theme.js');
    expect(html).not.toContain('/static/dist/shared/i18n.js');
    expect(html).not.toContain('/static/dist/shared/markdown-renderer.js');
    expect(html).not.toContain('/static/dist/shared/upload-quota-dialog.js');
    expect(runtime).toContain("import 'virtual:mediaforge-theme';");
    expect(runtime).toContain("import 'virtual:mediaforge-i18n';");
    expect(config).toContain("'src/shared/markdown.js'");
    expect(runtime).not.toContain('window.MediaForgeUpload');
  });
});
